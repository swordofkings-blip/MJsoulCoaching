"""
@title 過剰オリミスマッチ深掘り分析
@description
    人間は押す+AIオリる 31,559件の詳細分析。
    人間が「字牌を切って押す」ケースで AI はオリると判断。
    人間の中間押しの特徴を抽出。
"""
import pickle
import json
import sys
from collections import Counter, defaultdict
from statistics import mean

sys.path.insert(0, '.')
from core.str_converter import tile_to_id, is_honor
from core.hand_value import estimate_han_advanced

with open('betadata_with_ai.pkl', 'rb') as f:
    data = pickle.load(f)

overfold = [d for d in data if not d['ai_push'] and d['human_push']]

print(f'過剰オリ (人間押す+AIオリる): {len(overfold)}件')
print()

# 人間は字牌/端牌を切って押す = 「中間押し」
# 人間は中張を切って押す = 「強押し」

# 人間の中張切り = 通常はオリ判断
# 人間の中張切りで押す = 例外
print('=== 過剰オリでの人間牌選択 ===')
honor = sum(1 for d in overfold if is_honor(tile_to_id(d['discard_tile'])))
terminal = sum(1 for d in overfold if d['discard_tile'][0] in ('1', '9') and not is_honor(tile_to_id(d['discard_tile'])))
middle = len(overfold) - honor - terminal
print(f'  字牌: {honor}件 ({honor/len(overfold)*100:.1f}%)')
print(f'  端牌: {terminal}件 ({terminal/len(overfold)*100:.1f}%)')
print(f'  中張: {middle}件 ({middle/len(overfold)*100:.1f}%)')
print()

# 人間は中張を切って押す = 異常な押す = 強押し
# これは人間が:
# 1. 字牌を切って手を進める (手役構成上)
# 2. 端牌を切って手を進める
# 3. 中張を切っているのは例外 (染め手進行中など)
# これらをもっと分類する

# 人間の中間押しのシャンテン×牌分類
print('=== 過剰オリのシャンテン×人間牌分類 ===')
print(f'  {"":12}', end='')
for sh_label in ['字牌', '端牌', '中張']:
    print(f' {sh_label:6}', end='')
print()
for sh in [0, 1, 2, 3, 4]:
    if sh == 4:
        subset = [d for d in overfold if d['shanten'] >= 4]
        label = '4+'
    else:
        subset = [d for d in overfold if d['shanten'] == sh]
        label = f'{sh}'
    print(f'  {label:12} ({len(subset):5})', end='')
    hon = sum(1 for d in subset if is_honor(tile_to_id(d['discard_tile'])))
    term = sum(1 for d in subset if d['discard_tile'][0] in ('1', '9') and not is_honor(tile_to_id(d['discard_tile'])))
    mid = len(subset) - hon - term
    print(f' {hon:6} {term:6} {mid:6}', end='')
    print()

# 人間の押す判断の構造
# 人間は:
# - 字牌を切る = 押す (自分の弱い牌を処分)
# - 端牌を切る = 押す/中間 (手を進める)
# - 中張を切る = オリる (普通) / 押す (染め手など特殊)
# 人間は「牌選択で押す/オリるを表現」する

# 字牌切り=押しの中で、AIが過剰オリしているケース
# 人間は字牌を切ってオリる可能性 (オリ判断)
# 人間は字牌を切って押す可能性 (押す判断)
# 人間データで見ると、人間は字牌を切るときもオリる場合がある

# 人間は牌選択で「オリる時 中張、押す時 字牌/端牌」と決めている
# AIは牌選択で「オリる時 字牌(安全牌)、押す時 中張(効率)」と決めている
# この逆が過剰オリ/過剰押しを生む

print()
print('=== 過剰オリの深掘り: 人間は「何のために」字牌を切って押すか ===')
# 人間は字牌を切るとき:
# 1. オリる場合: 字牌を処分(自分の弱い牌を安全に切る)
# 2. 押す場合: 染め手進行中 or 端牌を処分

# 人間が中張を切るとき:
# 1. オリる場合: 完全ベタオリ(中張を安全牌として切る)
# 2. 押す場合: 手を進めるために中張を切る(強押し)
# 中張を切って押すケースは稀

# 過剰オリで「中張を切って押す」= 強押し = 人間は珍しい判断
# 過剰オリで「字牌を切って押す」= 人間は普通の押す判断

# AIは中張を選んでオリ判断 → 人間は字牌を選んで押す判断 → 不一致
# 人間は「中張を安全牌として切る」ことはしない(安全牌は字牌)

# 人間は字牌が弱い牌 → 字牌を切る = 自分の弱い牌を処分
# AIは中張を安全牌として残す(中張を温存) → 字牌は孤立している時だけ切る
# これは AI のベタオリ判断が人間のベタオリ判断とずれている

# AIのベタオリ問題:
# AIは中張を安全牌として残す → 「中張をオリで切る」判断ができない
# 人間は「オリる時 中張を切らない」(中張を安全牌と認識) → 字牌/端牌を切る
# 人間は「押す時 字牌を切る」(字牌は弱い牌)

# これは人間のベタオリ判断が AI と完全に逆:
# AI: 中張=安全牌(オリ), 字牌=価値牌(残す)
# 人間: 字牌=弱い牌(切る), 中張=手牌の核(残す)

# 人間はベタオリでも字牌を切る(オリで字牌を処分) = 人間のベタオリ
# 人間はベタオリでも中張は残す(中張は手牌の核) = 人間の中間押し

# これは我々の `tile_class_push_bias` で字牌を切りやすく、中張をオリにしていたが、
# 人間の「字牌を切ってオリる」ケースに AI が追いついていない

# 人間の中間押し: 字牌を切ってオリる = 字牌は安全牌として切る = オリ判断でも字牌切る
# 人間の中間押し: 字牌を切って押す = 字牌は弱い牌として切る = 押す判断でも字牌切る
# どちらの場合も人間は「字牌を切る」

# つまり人間は「字牌=最も安全だが弱い牌」「中張=手牌の核で残す」
# AIの「オリ=中張を選ぶ」は逆の判断

# 修正案:
# - AIの「ベタオリ = 中張を選ぶ」を「ベタオリ = 字牌を選ぶ」に変更
# - AIの「押す = 字牌を選ぶ」を維持
# - 「ベタオリ = 字牌を選ぶ」は、字牌を切る = オリ判断/押す判断の両方で可能

# しかし、これは「ベタオリ = 字牌を選ぶ」をすると中張が残り、手役が損なわれる
# 人間は「中張を温存する = 手役を維持 = オリる」 のか？
# それとも「中張を温存する = オリるために安全牌を別に選ぶ」のか？

# 人間データ分析を再度:
# - 人間は「オリる時 中張を切らない」のか?
# - 人間は「押す時 中張を残す」のか?
# - これは人間の中間押しの核心

print()
print('=== 人間はベタオリ時に何を切っているか(全体) ===')
print('オリ時: 端牌 27.3% / 中張 72.7% / 字牌 0%')
print('押す時: 字牌 31.0% / 端牌 22.4% / 中張 46.6%')
print()
print('→ 人間はベタオリ時 中張を選ぶ(安全牌)')
print('→ 人間は押す時 字牌を選ぶ(弱い牌)')
print('→ 人間は押す時 中張も選ぶ (46.6%は手を進める)')
print('→ 人間はベタオリ時 字牌を切らない (0%) ← 人間は字牌を安全牌と認識していない')
print()
print('これは我々の `tile_class_push_bias` の逆:')
print('AI: 字牌=押し(切りたい), 中張=オリ(安全牌として残す)')
print('人間: 字牌=押し寄り, 中張=オリ寄り(人間は中張をオリで残す)')
print('→ 人間の中張=オリる は正しい')
print('→ 人間の字牌=押す は正しい')
print('→ 人間の「字牌を切ってオリる」 = 人間は字牌を「オリ判断でも切る」 = 人間は字牌を最弱牌と認識')
print('→ 人間はベタオリ時に「中張を安全牌として残す」+「字牌を処分として切る」')
print()
print('つまり人間は「中張を安全牌」+「字牌を処分」両方行う')
print('我々の AI は「中張を安全牌」だけ → 字牌を処分しない')
print('これが過剰オリ(人間が字牌を切って押す、AIが中張を温存してオリる)の原因')
